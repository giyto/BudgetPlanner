package ru.hznik.budget.domain.security

/** Можно ли открыть базу (design.md add-data-protection, решение 2). */
enum class DatabaseState {
    /** Ключ есть и база открывается, или базы ещё нет. */
    READY,

    /** Файл базы зашифрован, а ключа нет или он не подходит: показывается экран «Не удалось открыть данные». */
    KEY_LOST,

    /** Временный сбой: данные, возможно, целы; показывается «Попробовать снова», удалять их не предлагается. */
    ERROR,
}

/** Подготовка зашифрованной базы до первого обращения к Room. */
interface DatabaseAccess {
    /** Проверяет ключ и базу, при необходимости переносит открытую базу в зашифрованную. Повторный вызов дешёвый. */
    suspend fun open(): DatabaseState

    /** «Удалить данные и начать заново»: удаляет базу, ключ и настройки; новый ключ создаст следующий [open]. */
    suspend fun wipe()
}
